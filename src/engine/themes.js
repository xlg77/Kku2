// 단어의 첫 글자로 정하는 조각 번호(0~254). 한글 44자씩 한 조각, 한글이 아니면 254.
export const THEME_SHARDS = 255;
export function themeShard(word) {
  const i = (word ? word.codePointAt(0) : 0) - 0xac00;
  return i < 0 || i >= 11172 ? 254 : Math.floor(i / 44);
}

// 조각 파일 한 줄: <단어>\t<주제번호,주제번호,...>
export function parseThemeShard(text) {
  const m = new Map();
  for (const line of text.split('\n')) {
    const t = line.indexOf('\t');
    if (t < 0) continue;
    m.set(line.slice(0, t), line.slice(t + 1).split(',').map(Number));
  }
  return m;
}
